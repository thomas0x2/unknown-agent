const FRAME_MS = 3000;
const CYCLE_MS = FRAME_MS * 3;

const escAttr = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!));
/** this page load's draw: slot key → ad. Cleared by newPageLoad(), so re-renders keep their ads. */
const drawn = new Map<string, Ad>();

/** Call on every navigation (including revisiting the same URL): the next render draws fresh ads. */
export function newPageLoad(): void { drawn.clear(); }

/** Draw a random ad of one shape for one slot; ads already on the page are left out. */
export function pickAd(site: string, day: number, slot: AdSlot, n = 0, rand: () => number = Math.random): Ad {
  const key = `${site}:${slot}:${n}`;
  const had = drawn.get(key);
  if (had) return had;
  const onPage = new Set([...drawn.values()].map((a) => a.id));
  const live = POOLS[slot].filter((a) => (a.from ?? 1) <= day);
  const fresh = live.filter((a) => !onPage.has(a.id));
  const pool = fresh.length ? fresh : live;
  const ad = pool[Math.floor(rand() * pool.length) % pool.length];
  drawn.set(key, ad);
  return ad;
}

function decoHtml(d?: Deco): string {
  switch (d) {
    case 'robot': return '<span class="ad-robot" aria-hidden="true">🤖</span>';
    case 'coins': return `<span class="ad-coins" aria-hidden="true">${`<i>${TOKENS.dolr}</i>`.repeat(5)}</span>`;
    case 'steam': return '<span class="ad-steam" aria-hidden="true"><i></i><i></i><i></i></span>';
    case 'bubbles': return '<span class="ad-bubbles" aria-hidden="true"><i></i><i></i><i></i><i></i><i></i></span>';
    case 'sparkle': return '<span class="ad-sparkle" aria-hidden="true"><i>✦</i><i>✦</i><i>✦</i><i>✦</i></span>';
    case 'stripes': return '<span class="ad-stripes" aria-hidden="true"></span>';
    case 'siren': return '<span class="ad-siren" aria-hidden="true"></span>';
    case 'shine': return '<span class="ad-shine" aria-hidden="true"></span>';
    case 'ekg': return '<svg class="ad-ekg" viewBox="0 0 200 40" preserveAspectRatio="none" aria-hidden="true"><polyline pathLength="1" points="0,20 40,20 48,8 56,32 64,20 100,20 108,4 116,36 124,20 200,20"/></svg>';
    case 'stamp': return '<span class="ad-stamp" aria-hidden="true">DENIED</span>';
    case 'approved': return '<span class="ad-stamp ad-stamp-ok" aria-hidden="true">ASSIGNED</span>';
    case 'snow': return '<span class="ad-snow" aria-hidden="true"><i>❄</i><i>❄</i><i>❄</i><i>❄</i><i>❄</i></span>';
    default: return '';
  }
}

/**
 * One animated banner. `wide` is a leaderboard for the top of a page; `square` is a sidebar box.
 * `n` tells apart two slots of the same shape on one page.
 */
export function adHtml(site: string, day: number, slot: AdSlot, n = 0): string {
  const ad = pickAd(site, day, slot, n);
  const t = -(Date.now() % CYCLE_MS);
  const frames = ad.frames.map((f, i) => `<span class="ad-f" style="--i:${i}"><span>${f}</span></span>`).join('');
  const why = WHY[site] ?? 'You were targeted because you have eyes.';
  // a div, not an <a>: each site styles its own links (pills, rows) and an ad must look the same everywhere
  return `<div class="ad ad-${slot} ${ad.theme}" style="--ad-t:${t}ms" data-newtab="${escAttr(ad.href)}" role="link" aria-label="Advertisement: ${escAttr(ad.sponsor)}">
    ${decoHtml(ad.deco)}
    <span class="ad-tag" title="${escAttr(why)}">Ad · ${escAttr(ad.sponsor)} <i>ⓘ</i></span>
    ${adLogoHtml(ad.href)}
    <span class="ad-frames">${frames}</span>
    <span class="ad-cta${ad.cta_fx ? ' fx-' + ad.cta_fx : ''}">${escAttr(ad.cta)}</span>
    <span class="ad-fine">${escAttr(ad.fine)}</span>
  </div>`;
}

