/*
 * A repo's file tree on Forkyard: a folder per built feature, sub-folders for its parts, and a file
 * per component at the bottom. It's how the player finds what to name in a fix prompt.
 */
import type { AppInstance } from '../engine';
import type { AppTemplate, FeatureDef } from '../content/schema';

export interface TreeFile { path: string; feature: FeatureDef; label: string }
export interface TreeEntry { name: string; path: string; dir: boolean }

/** Every file in the repo, as `<feature>/<component path>.ts`, for the features the agent has pushed. */
export function repoFiles(app: AppInstance, tmpl: AppTemplate | undefined): TreeFile[] {
  return app.repo.flatMap((f) => {
    const def = tmpl?.features.find((d) => d.id === f.id);
    if (!def) return [];
    const comps = def.components?.length ? def.components : [{ id: 'index', label: def.description }];
    return comps.map((c) => ({ path: `${def.folder ?? def.name ?? f.id}/${c.id}.ts`, feature: def, label: c.label }));
  });
}

/** What's at a path: a folder's entries (folders first), a file, or nothing. '' is the repo root. */
export function treeAt(files: TreeFile[], path: string): { dir: TreeEntry[] } | { file: TreeFile } | null {
  const clean = path.replace(/^\/+|\/+$/g, '');
  const file = files.find((f) => f.path === clean);
  if (file) return { file };
  const prefix = clean ? `${clean}/` : '';
  const under = files.filter((f) => f.path.startsWith(prefix));
  if (!under.length) return null;
  const seen = new Map<string, TreeEntry>();
  for (const f of under) {
    const [name, ...rest] = f.path.slice(prefix.length).split('/');
    if (!seen.has(name)) seen.set(name, { name, path: prefix + name, dir: rest.length > 0 });
  }
  return { dir: [...seen.values()].sort((a, b) => Number(b.dir) - Number(a.dir) || a.name.localeCompare(b.name)) };
}

/** A stand-in for the component's source: its name and what it does, no implementation details. */
export function fileSource(file: TreeFile): string {
  const base = file.path.split('/').pop()!.replace(/\.ts$/, '');
  const fn = base.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
  return [
    `// ${file.label}`,
    `// part of ${file.feature.id}: ${file.feature.description}`,
    '',
    `export function ${fn === 'index' ? file.feature.id.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase()) : fn}(ctx: Context) {`,
    '  // generated by agent[bot]',
    '  …',
    '}',
  ].join('\n');
}
